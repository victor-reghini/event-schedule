export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('sincroniza_lang');
      if (saved && TRANSLATIONS[saved]) return saved;
      // Detect browser language
      const navLang = navigator.language?.slice(0, 2);
      if (navLang && TRANSLATIONS[navLang]) return navLang;
    } catch (e) {
      console.warn('Could not read lang from localStorage', e);
    }
    return 'pt';
  });

  const setLang = (newLang) => {
    if (TRANSLATIONS[newLang]) {
      setLangState(newLang);
      try {
        localStorage.setItem('sincroniza_lang', newLang);
      } catch (e) {
        console.warn('Could not save lang to localStorage', e);
      }
    }
  };

  const t = (key, params = {}) => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;
    let str = dict[key] || TRANSLATIONS.pt[key] || key;
    if (typeof str === 'string' && Object.keys(params).length > 0) {
      Object.entries(params).forEach(([k, val]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), val);
      });
    }
    return str;
  };

  const currentLanguage = LANGUAGES.find(l => l.code === lang) || LANGUAGES[0];
  const daysOfWeek = DAYS_BY_LANG[lang] || DAYS_BY_LANG.pt;
  const monthNames = MONTHS_BY_LANG[lang] || MONTHS_BY_LANG.pt;

  return (
    <I18nContext.Provider value={{
      lang,
      setLang,
      t,
      languages: LANGUAGES,
      currentLanguage,
      daysOfWeek,
      monthNames
    }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return context;
}
